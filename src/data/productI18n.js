export const localizeProduct = (product, lang = "uz") => {
  if (!product) return product;
  const tr = productI18n[lang]?.[product.id];
  const isUz = lang === "uz";
  return {
    ...product,
    name: tr?.name ?? product.name,
    unit: tr?.unit ?? product.unit,
    origin: tr?.origin ?? product.origin,
    tags: tr?.tags ?? product.tags,
    description: tr?.description ?? (isUz ? product.description : defaultDescription[lang] ?? product.description),
  };
};

export const localizeProducts = (list, lang = "uz") => list.map((p) => localizeProduct(p, lang));

export const localizeOrderItem = (item, lang = "uz") =>
  localizeProduct({ ...item, id: item.productId }, lang);
